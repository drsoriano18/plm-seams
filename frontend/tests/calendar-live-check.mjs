// Read-only smoke check using the project's seeded administrator account.
// Never confirms event actions or changes database rows.
import { readFile, mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const config = Object.fromEntries((await readFile('.env.local', 'utf8')).split(/\r?\n/).filter(line => line.includes('=')).map(line => { const index = line.indexOf('='); return [line.slice(0, index), line.slice(index + 1).trim()] }))
const seed = await readFile('../supabase/seed.sql', 'utf8')
const sample = seed.match(/\('PLM-OSDS-2016-02782',\s*'([^']+)',\s*'([^']+)'/)
const browser = await chromium.launch({ headless: true, channel: 'chrome' })
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, timezoneId: 'Asia/Manila' })
const page = await context.newPage()
const api = []
page.on('response', async response => { if (response.url().includes('/rest/v1/venue_booking')) api.push({ status: response.status(), body: await response.json() }) })
try {
  await page.goto('http://127.0.0.1:5173/admin/login')
  await page.getByLabel('PLM Email').fill(sample[1])
  await page.getByLabel('Password', { exact: true }).fill(sample[2])
  await page.getByRole('button', { name: 'Sign In', exact: true }).click()
  await page.waitForURL('**/admin/dashboard', { timeout: 15000 })
  await page.goto('http://127.0.0.1:5173/admin/calendar')
  await page.getByRole('combobox').selectOption('PLM-VENUE-10')
  await page.waitForTimeout(1500)
  assert.deepEqual(await page.locator('.admin-calendar-days .is-unavailable').allTextContents(), ['27', '29'])
  const bookedDate = page.locator('[data-date="2026-11-27"]')
  assert.equal(await bookedDate.evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(255, 215, 215)')
  await bookedDate.click()
  assert.equal(await page.locator('.slot-unavailable').count(), 2)
  await page.getByText('Confirmed reservation · EV-2026-001', { exact: true }).waitFor()
  console.log(JSON.stringify({ configuredProject: config.VITE_SUPABASE_URL, month: await page.locator('.admin-calendar-month').innerText(), redDates: await page.locator('.admin-calendar-days .is-unavailable').allTextContents(), api, errors: await page.locator('[role=alert]').allTextContents() }))
  await mkdir('verification.local', { recursive: true })
  await page.screenshot({ path: 'verification.local/calendar-live.png', fullPage: true })
  await page.goto('http://127.0.0.1:5173/admin/calendar/events')
  await page.getByRole('heading', { name: 'Approved Campus Events' }).waitFor()
  await page.waitForTimeout(1500)
  await page.screenshot({ path: 'verification.local/approved-events-live.png', fullPage: true })
  assert.equal(await page.locator('.approved-table th').count(), 6)
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  assert.equal(await page.locator('.approved-event-row').count(), 2)
  assert.equal(await page.getByRole('button', { name: 'Next page', exact: true }).isDisabled(), true)
  await page.getByRole('combobox', { name: 'Venue', exact: true }).selectOption('PLM-VENUE-10')
  assert.equal(await page.locator('.approved-event-row').count(), 3)
  assert.ok((await page.locator('.approved-event-row').allTextContents()).every(row => row.includes('GEE Audio Visual Room')))
  await page.getByRole('combobox', { name: 'Organizer unit', exact: true }).selectOption({ label: 'PLM Computer Science Society' })
  assert.equal(await page.locator('.approved-event-row').count(), 1)
  await page.getByRole('button', { name: 'View Details', exact: true }).click()
  await page.getByRole('heading', { name: 'Event Proposal Review - Approved', exact: true }).waitFor()
  assert.match(await page.locator('.proposal-breadcrumb').innerText(), /Calendar\s*\/\s*Manage Approved Events\s*\/\s*CSS Tech Summit/)
  await page.getByRole('link', { name: 'Manage Approved Events', exact: true }).click()
  await page.locator('.approved-event-row').filter({ hasText: 'CSS Tech Summit' }).getByRole('link').click()
  await page.locator('[data-date="2026-11-27"].is-unavailable.is-selected').waitFor()
  assert.equal(await page.getByRole('combobox').inputValue(), 'PLM-VENUE-10')
  await page.getByRole('button', { name: 'Next month', exact: true }).click()
  await page.locator('[data-date="2026-12-07"].is-unavailable').waitFor()
  await page.getByRole('button', { name: 'Next month', exact: true }).click()
  await page.locator('.admin-venue-calendar[aria-busy="false"]').waitFor()
  assert.equal(await page.locator('[role=alert]').count(), 0)
  assert.match(await page.locator('.admin-calendar-month').innerText(), /January 2027/)
  await page.goto('http://127.0.0.1:5173/admin/calendar/events')
  await page.locator('.approved-event-row').first().waitFor()
  for (const width of [1024, 768, 390]) {
    await page.setViewportSize({ width, height: 844 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Page overflow at ${width}px`)
  }
  await page.screenshot({ path: 'verification.local/approved-events-mobile.png', fullPage: true })
  console.log('PASS live confirmed booking colors, selected slots, December/January boundaries, venue/organizer filters, pagination, detail breadcrumb, booking links and mobile overflow')
  console.log(JSON.stringify({ rows: await page.locator('.approved-event-row').count(), errors: await page.locator('[role=alert]').allTextContents() }))
} finally { await browser.close() }
